  function downloadCsv() {
    const q = (v) => `"${String(v).replace(/"/g, '""')}"`;
    const titleOf = (r) => {
      const m = MISSIONS.find((x) => x.id === r.missionId);
      return m ? L(m.title) : r.mission;
    };
    const lines = [t('csvHead').map(q).join(';')].concat(store.log.map((r) => [
      r.name, r.cls, titleOf(r), r.stars, r.wrong, r.failed, r.seconds,
      new Date(r.startedAt).toLocaleString(locale()), new Date(r.finishedAt).toLocaleString(locale())
    ].map(q).join(';')));
    const blob = new Blob(['﻿' + lines.join('\r\n')], { type: 'text/csv;charset=utf-8' });
    const a = document.createElement('a');
    const name = (store.player.name || t('csvDefaultName')).replace(/[^\p{L}\p{N}_-]+/gu, '_');
    a.href = URL.createObjectURL(blob);
    a.download = `soberi-pc_${name}.csv`;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 0);
  }

