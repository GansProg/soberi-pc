  function briefHtml() {
    const m = session.mission;
    if (!m.brief) return '';
    let meters = '';
    if (m.budget) {
      const total = placedParts().reduce((s, p) => s + (p.price || 0), 0);
      const over = total > m.budget;
      const pct = Math.min(100, (total / m.budget) * 100);
      const draw = placedParts().reduce((s, p) => s + (p.watts || 0), m.board.watts || 0);
      const need = Math.ceil((draw * POWER_MARGIN) / 10) * 10;
      const psu = findPlacedType('psu');
      const psuBad = psu && psu.capacity < need;
      const ofText = lang === 'kk' ? `/ ${money(m.budget)}` : `из ${money(m.budget)}`;
      meters = `<dl class="meters">
        <div class="meter">
          <dt>${t('cost')}</dt>
          <dd class="${over ? 'is-bad' : ''}">${money(total)} <span class="unit">${ofText}</span>${over ? ` <span>${t('over', money(total - m.budget))}</span>` : ''}</dd>
          <div class="track${over ? ' is-bad' : ''}" aria-hidden="true"><span style="width:${pct}%"></span></div>
        </div>
        <div class="meter">
          <dt>${t('drawLabel')}</dt>
          <dd>${draw} Вт <span class="unit">${t('needPsu', need)}</span></dd>
        </div>
        <div class="meter">
          <dt>${t('psuLabel')}</dt>
          <dd class="${psuBad ? 'is-bad' : ''}">${psu ? `${psu.capacity} Вт${psuBad ? ` — ${t('tooLow')}` : ''}` : `<span class="unit">${t('notChosen')}</span>`}</dd>
        </div>
      </dl>`;
    }
    return `<div class="brief"><h2>${m.budget ? t('briefOrder') : t('briefBoard')}</h2><p>${esc(L(m.brief))}</p>${meters}</div>`;
  }

