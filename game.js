  function validate(part, slot) {
    const m = session.mission;
    const items = session.placed[slot.id];

    if (m.layout === 'mobo') {
      if (part.kind === 'device') {
        return { ok: false, mistake: true, text: both(() => t('external', pName(part))) };
      }
      if (!slot.accepts.includes(part.type)) {
        return { ok: false, mistake: true, text: both(() => t('wrongSlot', L(slot.desc), TYPES[part.type])) };
      }
      const layer = slot.accepts.indexOf(part.type);
      const sameType = items.map(partById).find((p) => p.type === part.type);
      if (sameType) {
        return { ok: false, mistake: false, text: both(() => t('occupied', pName(sameType))) };
      }
      if (layer > 0 && items.length < layer) {
        return { ok: false, mistake: true, text: UI.coolerFirst };
      }
      return { ok: true, text: both(() => t('placed', pName(part), L(TYPES[part.type].fact))) };
    }

    if (m.layout === 'rear') {
      if (items.length) {
        return { ok: false, mistake: false, text: both(() => t('portBusy', pName(partById(items[0])))) };
      }
      if (part.plug !== slot.port) {
        return { ok: false, mistake: true, text: both(() => t('wrongPort', L(PORTS[slot.port].desc), pName(part), L(PORTS[part.plug].name))) };
      }
      return { ok: true, text: both(() => t('plugged', pName(part), L(PORTS[slot.port].name), L(IO[part.io].long))) };
    }

    if (part.io !== slot.io) {
      return { ok: false, mistake: true, text: both(() => t('wrongBin', L(part.why), L(IO[part.io].long))) };
    }
    return { ok: true, text: both(() => t('rightBin', L(part.why))) };
  }

