  function route() {
    if (dialog.open) dialog.close();
    session = null;
    const hash = location.hash || '#/';
    const mm = hash.match(/^#\/mission\/([\w-]+)/);
    if (mm) {
      const m = MISSIONS.find((x) => x.id === mm[1]);
      if (m) renderMission(m); else renderHome();
    } else if (hash.startsWith('#/results')) {
      renderResults();
    } else {
      renderHome();
    }
    renderRank();
    window.scrollTo(0, 0);
    if (document.readyState === 'complete' && hash !== '#/' && location.hash) app.focus({ preventScroll: true });
  }

  // Switch language without losing a mission in progress.
  function setLang(code) {
    if (code === lang) return;
    lang = code;
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
    applyStatic();
    renderRank();
    const y = window.scrollY;
    if (session) {
      renderMission(session.mission, true);
      if (dialog.open && lastPost) openPost();
    } else if ((location.hash || '#/').startsWith('#/results')) {
      renderResults();
    } else {
      renderHome();
    }
    window.scrollTo(0, y);
    const btn = $(`#lang [data-lang="${code}"]`);
    if (btn) btn.focus({ preventScroll: true });
  }

