  function place(partId, slotId) {
    const part = partById(partId);
    const slot = slotById(slotId);
    if (!part || !slot) return;
    const res = validate(part, slot);
    if (!res.ok) {
      if (res.mistake) session.wrong += 1;
      setStatus('error', res.text);
      shake(slotId);
      return;
    }
    session.placed[slotId].push(partId);
    session.selected = null;
    refresh(`slot:${slotId}`);
    setStatus('ok', res.text);
  }

  function removeFromSlot(slotId, partId) {
    const items = session.placed[slotId];
    let id = partId;
    if (!id) {
      for (let i = items.length - 1; i >= 0; i -= 1) {
        if (!partById(items[i]).pre) { id = items[i]; break; }
      }
    }
    if (!id) {
      setStatus('info', UI.preinstalled);
      return;
    }
    const part = partById(id);
    if (session.mission.layout === 'mobo' && part.type === 'cpu' && items.some((x) => partById(x).type === 'cooler')) {
      setStatus('info', UI.coolerOnTop);
      return;
    }
    session.placed[slotId] = items.filter((x) => x !== id);
    refresh(`slot:${slotId}`);
    setStatus('info', both(() => t('removed', pName(part))));
  }

  function select(partId) {
    session.selected = session.selected === partId ? null : partId;
    refresh(`part:${partId}`);
    if (session.selected) {
      const p = partById(partId);
      const layout = session.mission.layout;
      const whereKey = layout === 'bins' ? 'whereBins' : layout === 'rear' ? 'wherePort' : 'whereBoard';
      setStatus('info', both(() => t('selected', pName(p), t(whereKey))));
    }
  }

  /* =========================================================
     Checks (the power button)
     ========================================================= */
  function runChecks() {
    const m = session.mission;
    const lines = [];
    const errors = [];

    if (m.layout === 'mobo') {
      m.required.forEach((type) => {
        const p = findPlacedType(type);
        const line = { label: L(TYPES[type].label), value: p ? pName(p) : t('notFound'), ok: !!p };
        if (!p) errors.push(L(TYPES[type].missing));
        if (p && m.board) {
          if (type === 'cpu' && p.socket !== m.board.socket) {
            line.ok = false;
            line.value = t('badSocketLine', pName(p));
            errors.push(t('badSocket', pName(p), p.socket, m.board.socket));
          }
          if (type === 'ram' && p.mem !== m.board.mem) {
            line.ok = false;
            line.value = t('badMemLine', pName(p));
            errors.push(t('badMem', p.mem, m.board.mem));
          }
        }
        lines.push(line);
      });

      if (m.power) {
        const draw = placedParts().reduce((s, p) => s + (p.watts || 0), m.board.watts || 0);
        const need = Math.ceil((draw * POWER_MARGIN) / 10) * 10;
        const psu = findPlacedType('psu');
        if (psu) {
          const ok = psu.capacity >= need;
          lines.push({ label: t('powerLine'), value: t('powerValue', need, psu.capacity), ok });
          if (!ok) errors.push(t('powerError', draw, need, psu.capacity));
        }
      }

      if (m.budget) {
        const total = placedParts().reduce((s, p) => s + (p.price || 0), 0);
        const ok = total <= m.budget;
        lines.push({ label: t('budgetLine'), value: t('of', money(total), money(m.budget)), ok });
        if (!ok) errors.push(t('budgetError', money(total), money(total - m.budget)));
      }
    }

    if (m.layout === 'rear') {
      m.parts.forEach((p) => {
        const slotId = Object.keys(session.placed).find((s) => session.placed[s].includes(p.id));
        lines.push({ label: pName(p), value: slotId ? `${L(PORTS[slotById(slotId).port].label)}, ${L(IO[p.io].label).toLowerCase()}` : t('notPlugged'), ok: !!slotId });
        if (!slotId) errors.push(t('notPluggedError', pName(p), L(PORTS[p.plug].name)));
      });
    }

    if (m.layout === 'bins') {
      const left = shelfParts();
      BIN_SLOTS.forEach((b) => {
        const names = session.placed[b.id].map((id) => pName(partById(id)));
        lines.push({ label: L(IO[b.io].label), value: names.length ? names.join(', ') : t('binEmpty'), ok: true });
      });
      if (left.length) {
        lines.push({ label: t('notSorted'), value: left.map(pName).join(', '), ok: false });
        errors.push(t('notSortedError', left.map((p) => pName(p).toLowerCase()).join(', ')));
      }
    }

    return { lines, errors };
  }

  function starsFor(errorsCount) {
    if (errorsCount === 0) return 3;
    if (errorsCount <= 2) return 2;
    return 1;
  }

  let lastPost = null;

  function powerOn() {
    const m = session.mission;
    const { errors } = runChecks();
    const ok = errors.length === 0;
    if (!ok) session.failed += 1;

    let result = null;
    if (ok) {
      const seconds = Math.round((Date.now() - session.startedAt) / 1000);
      const errs = session.wrong + session.failed;
      const stars = starsFor(errs);
      const before = totalStars();
      const prev = store.progress[m.id] || {};
      store.progress[m.id] = { stars: Math.max(prev.stars || 0, stars), done: true };
      store.log.push({
        name: store.player.name || '',
        cls: store.player.cls || '',
        missionId: m.id,
        mission: L(m.title),
        stars,
        wrong: session.wrong,
        failed: session.failed,
        seconds,
        startedAt: new Date(session.startedAt).toISOString(),
        finishedAt: new Date().toISOString()
      });
      save();
      const after = totalStars();
      result = { stars, seconds, errs, rankUp: rankFor(after) !== rankFor(before) ? after : null };
      renderRank();
    }

    lastPost = { result };
    openPost();
  }

